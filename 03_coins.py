maxint = 10**9

def min_coins (coins, amount):
    dp = [maxint] * (amount + 1)
    dp[0] = 0
    for i in range(1, amount + 1):
        for coin in coins:
            if coin <= i:
                dp[i] = min(dp[i], dp[i-coin] + 1)

    if dp[amount] == maxint:
        return -1
    return dp[amount]

# dp - массив, где на i-ом месте стоит минимальное кол-во монет, чтобы составить сумму, равную i
# в этом массиве у нас лежат оптимальные решеение задачи для суммы, равной i
# Поэтому чтобы получить сумму i, мы берем монету и добавляем ее к оптимальному решению для суммы i-coin. 
# Кол-во монет увеличится на единицу. 
# Чтобы найти минимальное кол-во монет - берем минимум из старого оптимального пути для суммы i и оптимального решения для суммы i-coin, 

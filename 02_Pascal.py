n = int(input())
dp = []
for i in range(n):
    row = [0] * (i + 1)
    for j in range(i + 1):
        if (j == 0) or (i == j):
            row[j] = 1
        else:
            row[j] = dp[i-1][j-1] + dp[i-1][j]
    dp.append(row)

# i-ая строка строится так: j-ый элемент сроки равен сумме элементов i-1 строки на позициях j-1 и j (если j - крайний элемент строки, он равен 1)  
# Сложность: О(n^2), Так как два вложенных цикла по n

def find_max_up(arr):
    if len(arr) == 0:
        return 0
    if len(arr) == 1:
        return 1
    dp = [1] * len(arr)
    for i in range(1, len(arr)):
        if arr[i-1] < arr[i]:
            dp[i] = dp[i-1] + 1
    return max(dp)
# последовательность не может быть меньше 0 (если данный массив не пустой), поэтому инициализируем вспомогательный массив единицами
# на i-ом элементе вспомогательного массива у нас хранится длина возрастающей пос-ти, которая заканчивается на arr[i],
# поэтому если последовательность продолжается, то мы увеличиваем длину посл-ти на единицу и записываем в текущую ячейку, 
# если нет - в следующую ячейку записываем единицу (минимальную длину посл-ти)
# Максимальная длина - максимальный элемент в вспомогательном масстве
